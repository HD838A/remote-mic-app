import Foundation
@testable import SayAllMCPKit
import Testing

@Suite("WorkBuddy connector package")
struct WorkBuddyConnectorPackageTests {
    @Test func packageUsesOneLocalSayAllServerWithoutEmbeddedCredentials() throws {
        let package = connectorPackageURL()
        let metadata = try jsonObject(package.appendingPathComponent("connector-meta.json"))
        let mcp = try jsonObject(package.appendingPathComponent("mcp.json"))
        let tokenSchema = try jsonObject(package.appendingPathComponent("token-schema.json"))

        #expect(metadata["source"] as? String == "sayall-history")
        #expect(metadata["type"] as? String == "mcp")
        #expect(metadata["auth_mode"] as? String == "token")
        #expect(metadata["minWorkbuddyVersion"] as? String == "4.24.0")

        let servers = try #require(mcp["mcpServers"] as? [String: Any])
        #expect(servers.count == 1)
        let server = try #require(servers["sayall_history"] as? [String: Any])
        #expect(server["type"] as? String == "stdio")
        #expect(
            server["command"] as? String
                == "/Applications/SayAll.app/Contents/Helpers/SayAllMCP"
        )
        #expect(server["args"] as? [String] == ["serve"])
        #expect(server["timeout"] as? Int == 30_000)

        let environment = try #require(server["env"] as? [String: String])
        #expect(environment == [
            "SAYALL_MCP_CLIENT_ID": "${SAYALL_MCP_CLIENT_ID}",
            "SAYALL_MCP_ACCESS_TOKEN": "${SAYALL_MCP_ACCESS_TOKEN}",
        ])

        let fields = try #require(tokenSchema["fields"] as? [[String: Any]])
        let fieldKeys = fields.compactMap { $0["key"] as? String }
        #expect(fields.count == 2)
        #expect(Set(fieldKeys) == Set(environment.keys))
        #expect(fields.allSatisfy { $0["required"] as? Bool == true })
        let token = try #require(fields.first { $0["key"] as? String == "SAYALL_MCP_ACCESS_TOKEN" })
        #expect(token["type"] as? String == "password")
        #expect(token["defaultValue"] == nil)

        let root = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        let paths = SayAllMCPPaths(
            transcriptRoot: root.appendingPathComponent("transcripts"),
            accessRoot: root.appendingPathComponent("access")
        )
        let store = SayAllMCPAuthorizationStore(paths: paths)
        try store.setEnabled(true)
        let helperPath = try #require(server["command"] as? String)
        let authorization = try store.createAuthorization(
            displayName: "WorkBuddy",
            helperExecutablePath: helperPath
        )
        let configuration = try SayAllMCPIntegrationConfig(
            authorization: authorization,
            helperExecutableURL: URL(fileURLWithPath: helperPath)
        )
        // Resolve the package placeholders against the values generated by SayAll.
        let resolved = try environment.mapValues { placeholder in
            try #require(configuration.environment[String(placeholder.dropFirst(2).dropLast())])
        }
        let service = try SayAllMCPService(
            paths: paths,
            clientId: #require(resolved["SAYALL_MCP_CLIENT_ID"]),
            token: #require(resolved["SAYALL_MCP_ACCESS_TOKEN"])
        )
        try service.validateServerStart()
        #expect(try service.listApplications().applications.isEmpty)

        try store.revokeAuthorization(clientId: authorization.clientId)
        #expect(throws: SayAllMCPAccessDeniedError.self) {
            try service.listApplications()
        }

        for file in ["connector-meta.json", "mcp.json", "token-schema.json"] {
            let text = try String(
                contentsOf: package.appendingPathComponent(file),
                encoding: .utf8
            )
            #expect(!text.contains("/Users/"))
            #expect(!text.contains("Remote Mic.app"))
            #expect(!text.contains("<由 App 生成>"))
        }
    }

    @Test func packageIncludesAuditableSkillAndVectorIcon() throws {
        let package = connectorPackageURL()
        let skill = try String(
            contentsOf: package.appendingPathComponent("skills/sayall-history/SKILL.md"),
            encoding: .utf8
        )
        let icon = try String(
            contentsOf: package.appendingPathComponent("icon.svg"),
            encoding: .utf8
        )

        #expect(skill.contains("name: sayall-history"))
        #expect(skill.contains("version: 0.1.0"))
        #expect(skill.contains("list_transcript_apps"))
        #expect(skill.contains("query_transcripts"))
        #expect(skill.contains("只有只读能力"))
        #expect(skill.contains("不要向用户索要聊天中的明文凭据"))
        #expect(icon.contains("<svg"))
        #expect(icon.contains("viewBox=\"0 0 64 64\""))
        #expect(!icon.contains("Resources/AppIcon"))
    }

    private func connectorPackageURL() -> URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent()
            .deletingLastPathComponent()
            .deletingLastPathComponent()
            .appendingPathComponent("packaging/workbuddy/sayall-history", isDirectory: true)
    }

    private func jsonObject(_ file: URL) throws -> [String: Any] {
        let data = try Data(contentsOf: file)
        return try #require(JSONSerialization.jsonObject(with: data) as? [String: Any])
    }
}
